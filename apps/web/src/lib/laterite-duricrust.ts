export function filterLateriteDuricrustSites(
  sites: LateriteDuricrustSite[] = LATERITE_DURICRUST_SITES,
  filters: {
    country?: string;
    duricrustType?: string;
    difficulty?: string;
    search?: string;
  } = {}
): LateriteDuricrustSite[] {
  const { country, duricrustType, difficulty, search } = filters;
  const normalizedSearch = search?.trim().toLowerCase() ?? '';

  return sites.filter((site) => {
    if (country && country !== 'all' && site.country !== country) {
      return false;
    }
    if (
      duricrustType &&
      duricrustType !== 'all' &&
      site.duricrustType !== duricrustType
    ) {
      return false;
    }
    if (difficulty && difficulty !== 'all' && site.difficulty !== difficulty) {
      return false;
    }
    if (normalizedSearch.length > 0) {
      const haystack = [
        site.name,
        site.cratonProvince,
        site.country,
        site.region,
        site.duricrustType,
        site.description,
      ]
        .join(' ')
        .toLowerCase();
      if (!haystack.includes(normalizedSearch)) {
        return false;
      }
    }
    return true;
  });
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(Math.max(value, min), max);
}

function roundTo(value: number, decimals: number): number {
  const factor = 10 ** decimals;
  return Math.round(value * factor) / factor;
}

export function calculateLateriteDuricrust(
  input: LateriteDuricrustInput
): LateriteDuricrustAnalysis {
  const {
    pisoliteGravelDepthMm,
    scarpSlopeAngleDeg,
    saproliteUndercutSpanM,
    surfaceRockTempC,
    convectiveStormProximityKm,
  } = input;

  if (
    !Number.isFinite(pisoliteGravelDepthMm) ||
    pisoliteGravelDepthMm < 0 ||
    pisoliteGravelDepthMm > 85
  ) {
    throw new Error(
      'Invalid pisoliteGravelDepthMm: must be a finite number between 0 and 85 mm.'
    );
  }

  if (
    !Number.isFinite(scarpSlopeAngleDeg) ||
    scarpSlopeAngleDeg < 5 ||
    scarpSlopeAngleDeg > 55
  ) {
    throw new Error(
      'Invalid scarpSlopeAngleDeg: must be a finite number between 5 and 55 degrees.'
    );
  }

  if (
    !Number.isFinite(saproliteUndercutSpanM) ||
    saproliteUndercutSpanM < 0.0 ||
    saproliteUndercutSpanM > 6.5
  ) {
    throw new Error(
      'Invalid saproliteUndercutSpanM: must be a finite number between 0.0 and 6.5 meters.'
    );
  }

  if (
    !Number.isFinite(surfaceRockTempC) ||
    surfaceRockTempC < 22 ||
    surfaceRockTempC > 72
  ) {
    throw new Error(
      'Invalid surfaceRockTempC: must be a finite number between 22 and 72 °C.'
    );
  }

  if (
    !Number.isFinite(convectiveStormProximityKm) ||
    convectiveStormProximityKm < 1.0 ||
    convectiveStormProximityKm > 60.0
  ) {
    throw new Error(
      'Invalid convectiveStormProximityKm: must be a finite number between 1.0 and 60.0 km.'
    );
  }

  const gravelNorm = pisoliteGravelDepthMm / 85.0;
  const slopeNorm = (scarpSlopeAngleDeg - 5) / 50.0;
  const undercutNorm = saproliteUndercutSpanM / 6.5;
  const tempNorm = (surfaceRockTempC - 22) / 50.0;
  const stormInv = (60.0 - convectiveStormProximityKm) / 59.0;

  // 1. pisoliteBallBearingSlipPct (2 to 99 %)
  const rawSlip = 2 + gravelNorm * 55 + slopeNorm * 42;
  const pisoliteBallBearingSlipPct = roundTo(clamp(rawSlip, 2, 99), 1);

  // 2. cantileverRimCollapseProbabilityPct (1 to 99 %)
  const rawCollapse = 1 + undercutNorm * 62 + slopeNorm * 36;
  const cantileverRimCollapseProbabilityPct = roundTo(
    clamp(rawCollapse, 1, 99),
    1
  );

  // 3. ferruginousCompassDeviationDeg (1.5 to 38.0 deg)
  const rawDeviation = 1.5 + tempNorm * 20.5 + slopeNorm * 16.0;
  const ferruginousCompassDeviationDeg = roundTo(
    clamp(rawDeviation, 1.5, 38.0),
    1
  );

  // 4. mesaLightningThermalHazardScore (5 to 100)
  const rawLightningThermal = 5 + tempNorm * 45 + stormInv * 50;
  const mesaLightningThermalHazardScore = roundTo(
    clamp(rawLightningThermal, 5, 100),
    1
  );

  // 5. riskLevel
  let riskLevel: LateriteDuricrustAnalysis['riskLevel'];
  if (
    pisoliteBallBearingSlipPct >= 76 ||
    cantileverRimCollapseProbabilityPct >= 75 ||
    ferruginousCompassDeviationDeg >= 26.0 ||
    mesaLightningThermalHazardScore >= 80
  ) {
    riskLevel = 'critical';
  } else if (
    pisoliteBallBearingSlipPct >= 52 ||
    cantileverRimCollapseProbabilityPct >= 50 ||
    ferruginousCompassDeviationDeg >= 17.0 ||
    mesaLightningThermalHazardScore >= 58
  ) {
    riskLevel = 'high';
  } else if (
    pisoliteBallBearingSlipPct >= 28 ||
    cantileverRimCollapseProbabilityPct >= 26 ||
    ferruginousCompassDeviationDeg >= 9.5 ||
    mesaLightningThermalHazardScore >= 34
  ) {
    riskLevel = 'moderate';
  } else {
    riskLevel = 'low';
  }

  // 6. scarpStrategy
  const strategyMap: Record<
    LateriteDuricrustAnalysis['riskLevel'],
    LateriteDuricrustAnalysis['scarpStrategy']
  > = {
    critical: 'abort-rim-descend-gully-lightning-collapse',
    high: 'setback-6m-undercut-saprolite-cornice',
    moderate: 'sweep-pisolite-pea-gravel-trekking-poles',
    low: 'inland-cuirasse-slab-gnss-bearing',
  };

  const scarpStrategy = strategyMap[riskLevel];

  const warnings: string[] = [];
  if (riskLevel === 'critical') {
    warnings.push(
      `CRITICAL PISOLITE BALL-BEARING SLIP, CANTILEVERED CUIRASSE COLLAPSE & IRONSTONE LIGHTNING HAZARD (pisolite slip = ${pisoliteBallBearingSlipPct}%, rim collapse = ${cantileverRimCollapseProbabilityPct}%, compass deviation = ${ferruginousCompassDeviationDeg}°, lightning/thermal = ${mesaLightningThermalHazardScore}/100): Imminent boot slide on buckshot gravel or brittle failure of saprolite-undermined ferricrete shelf; abort scarp rim and descend sheltered joint gully immediately.`
    );
  } else if (riskLevel === 'high') {
    warnings.push(
      `HIGH SAPROLITE UNDERCUT CORNICE, PISOLITIC BREAKAWAY SLIP & REMANENT MAGNETIC ANOMALY RISK (pisolite slip = ${pisoliteBallBearingSlipPct}%, rim collapse = ${cantileverRimCollapseProbabilityPct}%, compass deviation = ${ferruginousCompassDeviationDeg}°, lightning/thermal = ${mesaLightningThermalHazardScore}/100): Maintain strict 6m horizontal setback from overhanging ferricrete/bauxite caprock and navigate exclusively via GNSS/sun-compass.`
    );
  } else if (riskLevel === 'moderate') {
    warnings.push(
      `Moderate pisolitic pea-gravel accumulation and ferruginous declination drift (pisolite slip = ${pisoliteBallBearingSlipPct}%, rim collapse = ${cantileverRimCollapseProbabilityPct}%, compass deviation = ${ferruginousCompassDeviationDeg}°, lightning/thermal = ${mesaLightningThermalHazardScore}/100): Sweep loose ironstone nodules ahead with trekking poles and verify magnetic bearings against GNSS.`
    );
  }

  if (saproliteUndercutSpanM >= 2.5 || surfaceRockTempC >= 55) {
    warnings.push(
      `PALLID-ZONE KAOLINITE PIPING & EXTREME FERRICRETE CONDUCTIVE HEAT (undercut span = ${saproliteUndercutSpanM}m, rock temp = ${surfaceRockTempC}°C): Subterranean seepage voids beneath indurated caprock and >55°C ironstone surfaces threaten sudden shelf fracture and EVA outsole delamination.`
    );
  }

  const recommendations: string[] = [
    `Execute ${scarpStrategy} protocol immediately (pisolite slip: ${pisoliteBallBearingSlipPct}%, cantilever collapse: ${cantileverRimCollapseProbabilityPct}%, compass deviation: ${ferruginousCompassDeviationDeg}°).`,
    pisoliteGravelDepthMm >= 20 || scarpSlopeAngleDeg >= 20
      ? `Clear ${pisoliteGravelDepthMm}mm spherical ironstone/bauxite pisolites from ${scarpSlopeAngleDeg}° ferricrete ramps using carbide pole tips and step onto bare indurated cuirasse ribs.`
      : `Traverse consolidated inland cuirasse slabs (${scarpSlopeAngleDeg}° slope, ${pisoliteGravelDepthMm}mm gravel cover) while maintaining visual clearance from breakaway lips.`,
    ferruginousCompassDeviationDeg >= 9.5 || convectiveStormProximityKm <= 25
      ? `Disregard magnetic needle headings (${ferruginousCompassDeviationDeg}° maghemite/hematite anomaly), lock multi-band GNSS + solar azimuths, and vacate exposed canga plateaus with storms at ${convectiveStormProximityKm}km.`
      : `Cross-check magnetic bearings against GNSS waypoints and monitor convective storm development (${convectiveStormProximityKm}km range, ${surfaceRockTempC}°C rock temp).`,
  ];

  return {
    pisoliteBallBearingSlipPct,
    cantileverRimCollapseProbabilityPct,
    ferruginousCompassDeviationDeg,
    mesaLightningThermalHazardScore,
    riskLevel,
    scarpStrategy,
    warnings,
    recommendations,
  };
}

